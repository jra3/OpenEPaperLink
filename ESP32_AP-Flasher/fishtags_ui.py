# PlatformIO pre-build script: gzip fishtags-ui/index.html into a C header in the build directory,
# so the fish-tags web UI ships inside firmware.bin and an OTA updates it with the firmware.
# The header defines FISHTAGS_UI_GZ, FISHTAGS_UI_LEN and FISHTAGS_UI_ETAG; web.cpp serves it at /.

import gzip
import hashlib
import os

Import("env")  # noqa: F821

src = os.path.join(env.subst("$PROJECT_DIR"), "fishtags-ui", "index.html")  # noqa: F821
out_dir = os.path.join(env.subst("$BUILD_DIR"), "fishtags_ui")  # noqa: F821
out = os.path.join(out_dir, "fishtags_ui.h")

with open(src, "rb") as f:
    data = gzip.compress(f.read(), compresslevel=9, mtime=0)
etag = hashlib.sha256(data).hexdigest()[:16]

lines = ["// generated by fishtags_ui.py from fishtags-ui/index.html", "#pragma once", "#include <stdint.h>", ""]
lines.append(f'#define FISHTAGS_UI_ETAG "\\"{etag}\\""')
lines.append(f"static const size_t FISHTAGS_UI_LEN = {len(data)};")
lines.append("static const uint8_t FISHTAGS_UI_GZ[] = {")
for i in range(0, len(data), 24):
    lines.append("    " + ",".join(str(b) for b in data[i : i + 24]) + ",")
lines.append("};")
header = "\n".join(lines) + "\n"

os.makedirs(out_dir, exist_ok=True)
# rewrite only on change, so an unchanged UI doesn't rebuild web.cpp
if not os.path.exists(out) or open(out).read() != header:
    with open(out, "w") as f:
        f.write(header)
    print(f"fishtags_ui: {len(data)} bytes gzipped, etag {etag}")

env.Append(CPPPATH=[out_dir])  # noqa: F821
